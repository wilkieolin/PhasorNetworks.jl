# Wilson score interval. The grid has 8 draws per cell, where the normal
# approximation is not usable and runs outside [0,1] at the saturated cells.
function wilson(k, n; z = 1.96)
    p = k / n; d = 1 + z^2 / n
    c = (p + z^2 / (2n)) / d
    h = z * sqrt(p * (1 - p) / n + z^2 / (4n^2)) / d
    return (max(0.0, c - h), min(1.0, c + h))
end

# Two-parameter logistic by IRLS.
function logistic_fit(x, y; iters = 100)
    b = [0.0, 0.0]
    for _ in 1:iters
        p = 1 ./ (1 .+ exp.(-(b[1] .+ b[2] .* x)))
        w = max.(p .* (1 .- p), 1e-9); r = y .- p
        s0 = sum(w); s1 = sum(w .* x); s2 = sum(w .* x .^ 2)
        det = s0 * s2 - s1^2; abs(det) < 1e-12 && break
        db = [(s2 * sum(r) - s1 * sum(r .* x)) / det,
              (-s1 * sum(r) + s0 * sum(r .* x)) / det]
        b .+= db; maximum(abs, db) < 1e-12 && break
    end
    return b
end

