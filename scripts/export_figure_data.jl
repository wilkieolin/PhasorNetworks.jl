const MACROS = Dict{String, Vector{Pair{String,String}}}()
macroset!(fig, name, val) = push!(get!(MACROS, fig, Pair{String,String}[]), name => val)

"""Write a whitespace table with a provenance comment. pgfplots skips `#` lines."""
function writedat(name::String, df::DataFrame; source::String, note::String = "")
    path = joinpath(DAT, name)
    open(path, "w") do io
        println(io, "# generated by scripts/export_figure_data.jl -- do not edit")
        println(io, "# source: ", source)
        isempty(note) || println(io, "# note: ", note)
        println(io, join(names(df), " "))
        for r in eachrow(df)
            println(io, join((v isa AbstractString ? v : @sprintf("%.6g", v) for v in r), " "))
        end
    end
    @printf("  %-28s %4d rows\n", name, nrow(df))
end

"""
Emit a closed polygon tracing hi forward then lo backward, so a band can be
drawn with a plain `\addplot[fill] table` -- no fillbetween library, and so no
change to the manuscript preamble.
"""
function writeband(name::String, x, lo, hi; source::String, note::String = "")
    bx = vcat(collect(x), reverse(collect(x)))
    by = vcat(collect(hi), reverse(collect(lo)))
    writedat(name, DataFrame(x = bx, y = by); source = source, note = note)
end

function write_macros()
    for (fig, defs) in MACROS
        path = joinpath(DAT, "$(fig)_macros.tex")
        open(path, "w") do io
            println(io, "% generated by scripts/export_figure_data.jl -- do not edit")
            for (n, v) in defs
                println(io, "\\newcommand{\\", n, "}{", v, "}")
            end
        end
        @printf("  %-28s %4d macros\n", "$(fig)_macros.tex", length(defs))
    end
end

