# Failure-rate strip, sharing the map's x axis.
function failband(df)
    m = combine(groupby(df, :omega_p), :fail => sum => :k, nrow => :n)
    sort!(m, :omega_p)
    lo = [wilson(r.k, r.n)[1] for r in eachrow(m)]
    hi = [wilson(r.k, r.n)[2] for r in eachrow(m)]
    DataFrame(wk = m.omega_p ./ KAPPA, rate = m.k ./ m.n, lo = lo, hi = hi)
end
