#!/usr/bin/env julia
# Aggregate results/*.csv into the tidy .dat tables the manuscript figures read.
#
# The figures are TikZ/pgfplots living in ICRC-LIEP-manuscript/figures/, so the
# paper rebuilds from its own sources. This script is the only bridge: nothing
# downstream of here recomputes an experiment, and no .tex file contains a
# hand-typed number taken from a result.
#
# Numbers that appear as TEXT in a figure (a fitted boundary, a mean difference)
# are emitted as LaTeX macros into figures/data/figN_macros.tex, so those are
# generated from the CSVs too rather than transcribed by hand.
#
#   julia --project=scripts scripts/export_figure_data.jl
#
# Env: LIEP_FIGDATA to redirect the output directory.

using Pkg
function find_repo_root(start_dir::String = pwd())
    dir = start_dir
    while !(isfile(joinpath(dir, "Project.toml")) && isdir(joinpath(dir, ".git")))
        parent = dirname(dir); parent == dir && error("no repo root"); dir = parent
    end
    return dir
end
