println("\nFigure 2:")
ft = CSV.read(joinpath(RES, "ep_analog_finetune", "analog_finetune_ddbaa3d.csv"), DataFrame)

# The sweep has been run more than once and appends, so some (pretrain, type,
# param, rep) keys appear twice -- the SAME damage draw measured against a
# different pretrained network, because BP pretraining is not bit-reproducible
# under multithreaded BLAS. Those are repeated measurements, not independent
# samples: keeping both would inflate n and understate the spread. As found,
# lognormal 0.03 carried 16 rows for 8 draws and lognormal 0.1 carried 9.
let before = nrow(ft)
    unique!(ft, [:pretrain, :impairment_type, :param, :rep])
    before == nrow(ft) ||
        @info "dropped $(before - nrow(ft)) duplicate (pretrain, type, param, rep) rows"
end
ft = ft[ft.pretrain .== "backprop", :]
const SERIES = [(:acc_clean, "clean"), (:acc_bp_ft, "bp"), (:acc_tuned, "ep"),
                (:acc_readout_only, "ro"), (:acc_impaired, "imp")]

# Severity means something different in each map. Three are dimensionless -- a
# log-space sigma for the multiplicative map, a fraction for the two stuck faults
# -- but the additive-Gaussian sigma is an ABSOLUTE standard deviation in weight
# units, so a bare sigma is uninterpretable next to the others. Divide it by the
# RMS weight, measured by the E2_NORMS_ONLY pass, and emit both.
RMSW = let f = joinpath(RES, "e2_norms", "damage_norms_ddbaa3d.csv")
    if isfile(f)
        d = CSV.read(f, DataFrame)
        "rms_clean" in names(d) ? Float64(first(d.rms_clean)) : NaN
    else
        NaN
    end
end
isnan(RMSW) || macroset!("fig2", "FigWrms", @sprintf("%.4f", RMSW))
isnan(RMSW) && @warn "no rms_clean yet -- rerun e2_full_sweep.jl with E2_NORMS_ONLY=1"
for t in sort(unique(ft.impairment_type))
    s = ft[ft.impairment_type .== t, :]
    g = combine(groupby(s, :param), nrow => :n,
        [c => median => Symbol(nm) for (c, nm) in SERIES]...,
        [c => (v -> quantile(v, 0.25)) => Symbol(nm * "lo") for (c, nm) in SERIES]...,
        [c => (v -> quantile(v, 0.75)) => Symbol(nm * "hi") for (c, nm) in SERIES]...)
    sort!(g, :param); rename!(g, :param => :sev)
    # sev_x is the severity the figure plots: sigma/RMS for additive Gaussian,
    # the raw parameter for every other map.
    g.sev_x = t == "gaussian" && !isnan(RMSW) ? g.sev ./ RMSW : copy(g.sev)
    writedat("fig2_rec_$(t).dat", g;
             source = "results/ep_analog_finetune/analog_finetune_$(gitrev_of(ft)).csv, pretrain=backprop",
             note = "median and IQR over $(maximum(g.n)) draws; clean/bp/ep/ro/imp")
end
# The sweep has been extended across several sessions and each invocation
# pretrains afresh; BP pretraining is not bit-reproducible (multithreaded BLAS
# reduction order depends on the thread count), so acc_clean varies slightly
# between runs. Quote the spread, not a single ceiling.
let cl = sort(unique(round.(Float64.(ft.acc_clean), digits = 4)))
    macroset!("fig2", "FigClean", @sprintf("%.3f", median(ft.acc_clean)))
    macroset!("fig2", "FigCleanLo", @sprintf("%.3f", minimum(cl)))
    macroset!("fig2", "FigCleanHi", @sprintf("%.3f", maximum(cl)))
    macroset!("fig2", "FigCleanRuns", string(length(cl)))
end
# Cells with fewer than MINREPS draws are held back from Figure 2(b) -- the same
# threshold the plotting script applies -- so the quoted draw count describes
# what is actually shown. Keep these two in step.
const FIG2_MINREPS = 4
let cnt = combine(groupby(ft, [:impairment_type, :param]), nrow => :n)
    shown = cnt[cnt.n .>= FIG2_MINREPS, :n]
    macroset!("fig2", "FigNdraw",
              minimum(shown) == maximum(shown) ? string(minimum(shown)) :
              string(minimum(shown)) * "--" * string(maximum(shown)))
    macroset!("fig2", "FigNdrawMin", string(minimum(shown)))
    macroset!("fig2", "FigNdrawMax", string(maximum(shown)))
    macroset!("fig2", "FigHeldBack", string(count(<(FIG2_MINREPS), cnt.n)))
end

pf_files = filter(f -> occursin(r"^lockin_paired_.*\.csv$", basename(f)),
                  readdir(joinpath(RES, "ep_analog_finetune"); join = true))
if isempty(pf_files)
    @warn "no lockin_paired_*.csv yet -- Figure 2's agreement panel has no data"
else
    src = last(sort(pf_files))
    pf = CSV.read(src, DataFrame)
    pf.delta = pf.acc_lockin .- pf.acc_static
    tid = Dict(t => i for (i, t) in enumerate(sort(unique(pf.impairment_type))))
    out = DataFrame(static = pf.acc_static, lockin = pf.acc_lockin,
                    tid = [tid[t] for t in pf.impairment_type], imp = pf.acc_impaired,
                    sev = pf.param, delta = pf.delta)
    writedat("fig2_paired.dat", out;
             source = "results/ep_analog_finetune/$(basename(src))",
             note = "paired: identical base network and identical damage draw; tid " *
                    join(("$i=$t" for (t, i) in sort(collect(tid), by = last)), ", "))

    # The grand mean is misleading on its own: the two estimators agree at mild
    # damage and diverge with severity, and almost all of the divergence is one
    # fault type. Emit the per-cell breakdown so the figure can show that.
    cells = combine(groupby(pf, [:impairment_type, :param]),
                    nrow => :n, :delta => mean => :mean,
                    :delta => median => :med,
                    :delta => (v -> length(v) > 1 ? 1.96 * std(v) / sqrt(length(v)) : NaN) => :ci)
    sort!(cells, [:impairment_type, :param])
    cells.tid = [tid[t] for t in cells.impairment_type]
    writedat("fig2_paired_cells.dat", select(cells, :tid, :param, :n, :mean, :med, :ci);
             source = "results/ep_analog_finetune/$(basename(src))",
             note = "mean(lockin - static) per (fault, severity) cell with 95% CI")

    d = pf.delta
    macroset!("fig2", "FigPairDelta", @sprintf("%+.3f", mean(d)))
    macroset!("fig2", "FigPairCI", @sprintf("%.3f", 1.96 * std(d) / sqrt(length(d))))
    macroset!("fig2", "FigPairN", string(length(d)))
    macroset!("fig2", "FigPairWins", string(count(>(0), d)))
    # the two extremes of the breakdown, which are what the panel is really about
    worstcell = cells[argmin(cells.mean), :]
    bestcell  = cells[argmax(cells.mean), :]
    macroset!("fig2", "FigPairWorst", @sprintf("%+.3f", worstcell.mean))
    macroset!("fig2", "FigPairWorstCell",
              "$(replace(worstcell.impairment_type, "_" => "\\_")) $(worstcell.param)")
    macroset!("fig2", "FigPairBest", @sprintf("%+.3f", bestcell.mean))
    macroset!("fig2", "FigPairBestCell",
              "$(replace(bestcell.impairment_type, "_" => "\\_")) $(bestcell.param)")
    mild = cells[cells.n .> 0 .&& abs.(cells.mean) .< 0.025, :]
    macroset!("fig2", "FigPairAgreeN", string(nrow(mild)))
    macroset!("fig2", "FigPairCellN", string(nrow(cells)))
end

