# Boundary: logistic in log10(omega_p) over eps >= 0.01. The eps dependence is
# NOT monotone -- eps >= 0.01 behaves identically while eps = 0.003 fails from
# below -- so a two-variable fit would impose a trend the data contradicts.
sub = grid[grid.eps .>= 0.01, :]
b = logistic_fit(log10.(Float64.(sub.omega_p)), Float64.(sub.fail))
